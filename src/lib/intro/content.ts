/** 버튼 — href가 없으면 아직 연결할 화면이 없다는 뜻이다 */
export type Cta = {
  label: string;
  href?: string;
};

/** 숫자 지표. 출처가 확정되기 전에는 pending으로 둔다 (PR-5). */
export type Stat = {
  value: string;
  label: string;
  /** 출처·기준일. 없으면 화면에 "출처 확인 중"으로 나온다. */
  source?: string;
  pending?: boolean;
};

export type IntroContent = {
  audience: Audience;
  /** 브라우저 탭 제목 */
  title: string;
  description: string;

  hero: {
    eyebrow: string;
    /** 줄바꿈 위치를 직접 잡으려고 배열로 둔다 */
    headline: string[];
    sub: string;
    primary: Cta;
    secondary: Cta;
  };

  stats: Stat[];

  /** "지금 이런 일이 벌어져요" */
  problems: { title: string; body: string }[];

  /** "이렇게 달라져요" — 3~4단계 */
  steps: { title: string; body: string }[];

  /** 기능 소개 — 좌우 번갈아 배치 */
  features: {
    tag: string;
    title: string;
    body: string;
    bullets: string[];
  }[];

  faq: { q: string; a: string }[];

  closing: {
    headline: string;
    sub: string;
    primary: Cta;
    secondary?: Cta;
  };
};

